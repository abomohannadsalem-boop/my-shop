-- Automatically assign stable, human-readable product codes without modifying products.id.
-- Existing products get codes derived from their current identity value.
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS product_code text;

UPDATE public.products
SET product_code = 'PRD-' || lpad(id::text, 6, '0')
WHERE product_code IS NULL OR btrim(product_code) = '';

CREATE UNIQUE INDEX IF NOT EXISTS products_product_code_unique_idx
  ON public.products (product_code);

ALTER TABLE public.products
  ALTER COLUMN product_code SET NOT NULL;

CREATE OR REPLACE FUNCTION public.assign_product_code()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    -- The identity column is generated by PostgreSQL; do not update or override it.
    NEW.product_code := 'PRD-' || lpad(NEW.id::text, 6, '0');
  ELSIF NEW.product_code IS DISTINCT FROM OLD.product_code THEN
    -- Product codes are generated by the database and cannot be edited manually.
    NEW.product_code := OLD.product_code;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS products_assign_product_code ON public.products;
CREATE TRIGGER products_assign_product_code
BEFORE INSERT OR UPDATE OF product_code ON public.products
FOR EACH ROW EXECUTE FUNCTION public.assign_product_code();

-- Keep a product-code snapshot on order lines so old order history remains readable.
ALTER TABLE public.order_items
  ADD COLUMN IF NOT EXISTS product_code text;

UPDATE public.order_items AS oi
SET product_code = p.product_code
FROM public.products AS p
WHERE oi.product_id = p.id
  AND (oi.product_code IS NULL OR btrim(oi.product_code) = '');
